"""Generate the all-public host block. No Borant ID or path-auth exceptions."""

import argparse
from settings import valid_host


def block(host, port):
    if not valid_host(host) or not 1024 <= port <= 65535:
        raise ValueError("Invalid host or unprivileged loopback port")
    return f"""# Generated by python -m deployment.caddy; all application paths are public.
# Replace the old host block, never add a duplicate host to the Caddyfile.
{host} {{
    encode zstd gzip
    request_body {{
        max_size 1KB
    }}
    reverse_proxy 127.0.0.1:{port} {{
        header_up -X-Borant-*
        header_up -Authorization
        header_up -Cookie
        transport http {{
            response_header_timeout 60s
        }}
    }}
}}
""".replace("    ", "\t")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--host", required=True)
    parser.add_argument("--port", type=int, default=8502)
    args = parser.parse_args()
    print(block(args.host, args.port), end="")


if __name__ == "__main__":
    main()
